<?php
require '../inc/auth.php';
require '../inc/connection.php';
require '../inc/facility_functions.php';

$pageTitle = 'Preventive Maintenance';

function pmScalar(mysqli $connection, string $sql)
{
    $result = mysqli_query($connection, $sql);
    $row = $result ? mysqli_fetch_assoc($result) : [];

    return $row['v'] ?? 0;
}

$uid = (int) ($_SESSION['user_id'] ?? 0);

$can = facilityHasRole(
    $connection,
    $uid,
    [
        'facility_officer',
        'facility_project_manager',
        'facility_admin'
    ]
);

facilityCsrfToken();

function pmFlash(string $type, string $message): void
{
    $_SESSION['flash_type'] = $type;
    $_SESSION['flash_text'] = $message;
}


/* ============================================================
   ACTIONS
============================================================ */

if (
    $_SERVER['REQUEST_METHOD'] === 'POST' &&
    $can
) {

    if (!facilityValidateCsrf()) {

        pmFlash(
            'error',
            'Invalid request.'
        );

        header(
            'Location: preventive_maintenance.php'
        );

        exit;
    }

    $action = $_POST['action'] ?? '';


    /* ========================================================
       GENERATE PM RUNS
    ========================================================= */

    if ($action === 'generate') {

        $due = mysqli_query(
            $connection,
            "
            SELECT *
            FROM facility_pm_schedules
            WHERE status = 'active'
            AND next_due_date <= DATE_ADD(
                CURDATE(),
                INTERVAL 14 DAY
            )
            "
        );

        $generated = 0;

        while (
            $due &&
            ($schedule = mysqli_fetch_assoc($due))
        ) {

            $runStatus =
                $schedule['next_due_date']
                < date('Y-m-d')
                    ? 'Overdue'
                    : (
                        $schedule['next_due_date']
                        === date('Y-m-d')
                            ? 'Due'
                            : 'Upcoming'
                    );

            $stmt = mysqli_prepare(
                $connection,
                "
                INSERT IGNORE INTO facility_pm_runs
                (
                    schedule_id,
                    due_date,
                    status
                )
                VALUES (?, ?, ?)
                "
            );

            mysqli_stmt_bind_param(
                $stmt,
                'iss',
                $schedule['id'],
                $schedule['next_due_date'],
                $runStatus
            );

            mysqli_stmt_execute($stmt);

            $generated +=
                mysqli_stmt_affected_rows($stmt) > 0
                    ? 1
                    : 0;
        }

        pmFlash(
            'success',
            "{$generated} PM run(s) generated."
        );
    }


    /* ========================================================
       CREATE WORK REQUEST
    ========================================================= */

    if ($action === 'create_request') {

        $runId = (int) (
            $_POST['run_id']
            ?? 0
        );

        $runResult = mysqli_query(
            $connection,
            "
            SELECT
                r.*,
                s.asset_id,
                s.maintenance_category_id,
                a.outlet_id,
                a.asset_code,
                a.asset_name

            FROM facility_pm_runs r

            INNER JOIN facility_pm_schedules s
                ON s.id = r.schedule_id

            INNER JOIN facility_assets a
                ON a.id = s.asset_id

            WHERE r.id = {$runId}

            LIMIT 1
            "
        );

        $run = $runResult
            ? mysqli_fetch_assoc($runResult)
            : null;

        if (
            $run &&
            !$run['maintenance_request_id']
        ) {

            $temporaryNumber =
                'TMP-' . uniqid();

            $subject =
                'Preventive Maintenance — '
                . $run['asset_code']
                . ' '
                . $run['asset_name'];

            $description =
                'Scheduled preventive maintenance generated by CMMS.';

            $requesterName =
                $_SESSION['fullname']
                ?? 'Facility Team';

            $emailResult = mysqli_query(
                $connection,
                "
                SELECT email
                FROM users
                WHERE id = {$uid}
                LIMIT 1
                "
            );

            $requesterEmail =
                $emailResult
                    ? (
                        mysqli_fetch_assoc(
                            $emailResult
                        )['email']
                        ?? 'facility@local'
                    )
                    : 'facility@local';

            $categoryId =
                $run[
                    'maintenance_category_id'
                ]
                ?: null;

            $stmt = mysqli_prepare(
                $connection,
                "
                INSERT INTO facility_maintenance_requests
                (
                    request_number,
                    request_type,
                    asset_id,
                    outlet_id,
                    requested_by,
                    contact_name,
                    contact_email,
                    subject,
                    description,
                    maintenance_category_id,
                    priority,
                    status
                )
                VALUES
                (
                    ?,
                    'preventive',
                    ?,
                    ?,
                    ?,
                    ?,
                    ?,
                    ?,
                    ?,
                    ?,
                    'Medium',
                    'Under Review'
                )
                "
            );

            mysqli_stmt_bind_param(
                $stmt,
                'siiissssi',
                $temporaryNumber,
                $run['asset_id'],
                $run['outlet_id'],
                $uid,
                $requesterName,
                $requesterEmail,
                $subject,
                $description,
                $categoryId
            );

            mysqli_stmt_execute($stmt);

            $maintenanceRequestId =
                mysqli_insert_id(
                    $connection
                );

            $requestNumber =
                facilityRequestNumber(
                    $maintenanceRequestId
                );

            $escapedNumber =
                mysqli_real_escape_string(
                    $connection,
                    $requestNumber
                );

            mysqli_query(
                $connection,
                "
                UPDATE facility_maintenance_requests
                SET request_number = '{$escapedNumber}'
                WHERE id = {$maintenanceRequestId}
                "
            );

            mysqli_query(
                $connection,
                "
                UPDATE facility_pm_runs
                SET
                    maintenance_request_id = {$maintenanceRequestId},
                    status = 'Scheduled'
                WHERE id = {$runId}
                "
            );

            facilityLog(
                $connection,
                $maintenanceRequestId,
                $uid,
                'Preventive maintenance request generated'
            );

            pmFlash(
                'success',
                "Created {$requestNumber}."
            );
        }
    }

    header(
        'Location: preventive_maintenance.php'
    );

    exit;
}


/* ============================================================
   PM RUNS
============================================================ */

$runs = mysqli_query(
    $connection,
    "
    SELECT
        r.*,
        s.frequency_value,
        s.frequency_unit,
        a.asset_code,
        a.asset_name,
        o.warehouse_name,
        m.request_number

    FROM facility_pm_runs r

    INNER JOIN facility_pm_schedules s
        ON s.id = r.schedule_id

    INNER JOIN facility_assets a
        ON a.id = s.asset_id

    INNER JOIN outlets o
        ON o.id = a.outlet_id

    LEFT JOIN facility_maintenance_requests m
        ON m.id = r.maintenance_request_id

    ORDER BY
        r.due_date ASC,
        a.asset_name ASC
    "
);


/* ============================================================
   SUMMARY
============================================================ */

$activeSchedules = (int) pmScalar(
    $connection,
    "
    SELECT COUNT(*) v
    FROM facility_pm_schedules
    WHERE status = 'active'
    "
);

$overdueSchedules = (int) pmScalar(
    $connection,
    "
    SELECT COUNT(*) v
    FROM facility_pm_schedules
    WHERE status = 'active'
    AND next_due_date < CURDATE()
    "
);

$dueToday = (int) pmScalar(
    $connection,
    "
    SELECT COUNT(*) v
    FROM facility_pm_schedules
    WHERE status = 'active'
    AND next_due_date = CURDATE()
    "
);

$upcoming = (int) pmScalar(
    $connection,
    "
    SELECT COUNT(*) v
    FROM facility_pm_schedules
    WHERE status = 'active'
    AND next_due_date > CURDATE()
    AND next_due_date <= DATE_ADD(
        CURDATE(),
        INTERVAL 14 DAY
    )
    "
);

$scheduledRequests = (int) pmScalar(
    $connection,
    "
    SELECT COUNT(*) v
    FROM facility_pm_runs
    WHERE maintenance_request_id IS NOT NULL
    "
);


